            for ($i = 1; $i <= $this->yyidx; $i++) {
                $ent = $this->yystack[$i];
                fprintf($this->yyTraceFILE, " %s", self::$yyTokenName[$ent->major]);
            }
            fprintf($this->yyTraceFILE, "\n");
        }
    }

