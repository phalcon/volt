function phvolt_ret_for_statement(
    &$ret,
    Token $variable,
    ?Token $key = null,
    array $expr = [],
    $if_expr = null,
    $block_statements = null,
    ?State $state = null,
): void
{
    $ret = [
        "type"     => Compiler::PHVOLT_T_FOR,
        "variable" => $variable->value,
