    unset($variable);

    if ($key) {
        $ret["key"] = $key->value;
        unset($key);
    }

    $ret["expr"] = $expr;

    if ($if_expr !== null) {
        $ret["if_expr"] = $if_expr;
    }

    $ret["block_statements"] = $block_statements;
    $ret["file"]             = $state->getActiveFile();
    $ret["line"]             = $state->getActiveLine();
}

