    {
        if ($this->yyidx < 0) {
            return 0;
        }

        $yytos = $this->yystack[$this->yyidx];

        if ($this->yyTraceFILE) {
            fprintf(
                $this->yyTraceFILE,
                "%sPopping %s\n",
                $this->yyTracePrompt,
                self::$yyTokenName[$yytos->major],
            );
        }

        $this->yy_destructor($yytos->major, $yytos->minor);
        unset($this->yystack[$this->yyidx]);
        $this->yyidx--;

        return $yytos->major;
